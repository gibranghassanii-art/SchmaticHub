const pages = { home, browse, schematic: detail, upload };
function route() {
  V?.dispose(); V = null; const [h, q] = (location.hash.slice(1) || '/').split('?'), [k, id] = h.split('/').filter(Boolean);
  scrollTo(0, 0); $('#nav').classList.remove('open'); $('#bg').setAttribute('aria-expanded', false);
  (pages[k || 'home'] || home)(id && decodeURIComponent(id), new URLSearchParams(q));
}
