// ---- Easy-to-change settings --------------------------------------------------------------
const SITE = { name: 'SchematicHub', repo: 'YOUR-USER/YOUR-REPO', pageSize: 6, maxMB: 50 };
const LOGO = `<svg viewBox="0 0 32 32" aria-hidden="true"><path d="M16 2 29 9v14l-13 7L3 23V9z" fill="#4ade5a"/><path d="M16 16 3 9m13 7 13-7m-13 7v14" stroke="#0d110e" stroke-width="2" fill="none"/></svg>`;
const VERSIONS = ['1.21.4', '1.21.1', '1.20.4', '1.20.1', '1.19.4', '1.18.2', '1.16.5'];
const CATEGORIES = ['Castles', 'Houses', 'Towers', 'Monuments', 'Fantasy', 'Redstone', 'Farms', 'Other'];
// --------------------------------------------------------------------------------------------

const app = document.getElementById('app'), $ = (s, r = document) => r.querySelector(s), $$ = (s, r = document) => [...r.querySelectorAll(s)];
// All user/JSON text goes through esc() before touching innerHTML -> no HTML/JS injection.
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const ls = { get: (k, d) => { try { return JSON.parse(localStorage.getItem('sh:' + k)) ?? d } catch { return d } }, set: (k, v) => { try { localStorage.setItem('sh:' + k, JSON.stringify(v)) } catch {} } };
const fmt = n => n >= 1e3 ? (n / 1e3).toFixed(1).replace('.0', '') + 'k' : n;
const bytes = n => n > 1e6 ? (n / 1e6).toFixed(1) + ' MB' : Math.ceil(n / 1e3) + ' KB';

let DB = [], V; const extra = [];                       // DB = data/schematics.json, extra = this-session uploads
const all = () => [...extra, ...DB], get = id => all().find(s => s.id === id);
const uniq = k => [...new Set(all().map(s => s[k]))].sort();
const liked = () => new Set(ls.get('liked', []));
const likes = s => s.likes + (liked().has(s.id) ? 1 : 0);
const dls = s => s.downloads + (ls.get('dl', {})[s.id] || 0);
const big = s => Math.max(s.dimensions.x, s.dimensions.y, s.dimensions.z);
const byNew = (a, b) => b.uploaded.localeCompare(a.uploaded), byDl = (a, b) => dls(b) - dls(a);

// ---- Cards (previews are real 3D renders, generated lazily when scrolled into view) --------
const card = s => `<a class="card" href="#/schematic/${encodeURIComponent(s.id)}">${s.demo ? '<i class="demo">DEMO</i>' : ''}
<div class="th" data-src="${esc(s.file)}" data-t="${esc(s.title)}"><span>Rendering preview…</span></div>
<div class="cb"><h3>${esc(s.title)}</h3><p class="by">by ${esc(s.author)} · Minecraft ${esc(s.minecraftVersion)} · ${s.dimensions.x}×${s.dimensions.y}×${s.dimensions.z}</p>
<p class="ds">${esc(s.description)}</p><p class="tg">${s.tags.slice(0, 4).map(t => `<i>${esc(t)}</i>`).join('')}</p>
<p class="st"><span>⬇ ${fmt(dls(s))}</span><span>♥ ${fmt(likes(s))}</span><b class="btn sm">View &amp; download</b></p></div></a>`;
const io = new IntersectionObserver(es => es.forEach(e => {
  if (!e.isIntersecting) return; io.unobserve(e.target); const el = e.target;
  thumb(el.dataset.src).then(u => {
    if (!u) { el.firstChild.textContent = 'No preview'; return }
    const i = new Image(); i.alt = '3D preview of ' + el.dataset.t; i.src = u; el.replaceChildren(i);
  });
}), { rootMargin: '200px' });
const lazy = r => $$('.th', r).forEach(e => io.observe(e));

// ---- Pages -----------------------------------------------------------------------------------
const sec = (t, l, list) => `<section class="sec"><div class="row"><h2>${t}</h2><a href="${l}">See all</a></div><div class="grid">${list.map(card).join('')}</div></section>`;
